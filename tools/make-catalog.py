#!/usr/bin/env python3
"""Merge the download manifests into standards/sources.json and standards/CATALOG.md.

The documents themselves stay in standards/specs/ (ignored): most are
copyrighted and may not be redistributed. sources.json records where each
came from and its SHA-256, so a checkout can fetch and verify its own copies.
"""
import glob, json, os, collections
root = os.path.join(os.path.dirname(__file__), "..", "standards")
rows = []
for m in sorted(glob.glob(os.path.join(root, "specs", "_manifest_*.json"))):
    rows += json.load(open(m))
rows.sort(key=lambda r: (r.get("domain", ""), r["id"]))
json.dump(rows, open(os.path.join(root, "sources.json"), "w"), indent=1, sort_keys=True)
count = collections.Counter(r["status"] for r in rows)
out = ["# Embedded-systems standards catalog", "",
       f"{len(rows)} standards: " + ", ".join(f"{n} {s}" for s, n in sorted(count.items())) + ".", "",
       "Generated by `tools/make-catalog.py` from `standards/sources.json`. Downloaded documents live in",
       "`standards/specs/<id>/` and are not tracked; paywalled ones are listed with their official source only.", ""]
domain = None
for r in rows:
    d = r.get("domain", "other")
    if d != domain:
        domain = d
        out += ["", f"## {d}", "", "| Standard | Publisher | Edition | Status | Source |", "|---|---|---|---|---|"]
    cell = lambda k: str(r.get(k) or "").replace("|", "/").replace("\n", " ")
    out.append(f"| {cell('title')} | {cell('publisher')} | {cell('edition')} | {cell('status')} | {cell('official_url')} |")
open(os.path.join(root, "CATALOG.md"), "w").write("\n".join(out) + "\n")
print(len(rows), dict(count))
